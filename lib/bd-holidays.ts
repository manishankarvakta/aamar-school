/**
 * Check if a given date is a Bangladesh public holiday
 * @param date - Date object or date string (YYYY-MM-DD)
 * @returns holiday name string or null
 */
export function getBDHoliday(date: Date | string): string | null {
  const dateStr =
    typeof date === "string"
      ? date
      : date.toISOString().split("T")[0];
  return BD_HOLIDAYS[dateStr] ?? null;
}

/**
 * Get all holidays for a given month/year
 * @param year - full year e.g. 2026
 * @param month - 1-indexed month e.g. 8 for August
 */
export function getBDHolidaysForMonth(
  year: number,
  month: number
): Record<number, string> {
  const result: Record<number, string> = {};
  const monthStr = month.toString().padStart(2, "0");
  const prefix = `${year}-${monthStr}-`;

  for (const [dateKey, name] of Object.entries(BD_HOLIDAYS)) {
    if (dateKey.startsWith(prefix)) {
      const day = parseInt(dateKey.split("-")[2], 10);
      result[day] = name;
    }
  }
  return result;
}
